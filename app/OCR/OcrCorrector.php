<?php

namespace App\OCR;

class OcrCorrector
{
    public static function correct(?string $text): ?string
    {
        if (!$text) {
            return $text;
        }

        /*
        |--------------------------------------------------------------------------
        | Các lỗi OCR thường gặp
        |--------------------------------------------------------------------------
        */

        $rules = [

            /*
            |--------------------------------------------------------------------------
            | Trường Đại học
            |--------------------------------------------------------------------------
            */

            '/TRUONG/u' => 'TRƯỜNG',
            '/CUU LONG/u' => 'CỬU LONG',
            '/DAI HOC/u' => 'ĐẠI HỌC',
            '/dai hoc/u' => 'đại học',

            /*
            |--------------------------------------------------------------------------
            | Họ tên
            |--------------------------------------------------------------------------
            */

            '/Ho va ten/u' => 'Họ và tên',
            '/Ho ten/u' => 'Họ tên',
            '/thi sinh/u' => 'thí sinh',

            /*
            |--------------------------------------------------------------------------
            | Địa chỉ
            |--------------------------------------------------------------------------
            */

            '/Noi sinh gin/u' => 'Nơi sinh:',
            '/Noi sinh gin/u' => 'Nơi sinh:',
            '/Noi sinh:/u' => 'Nơi sinh:',

            '/Dia chi/u' => 'Địa chỉ',

            '/Thuong tru/u' => 'Thường trú',

            '/Tinh\/TP/u' => 'Tỉnh/TP',

            /*
            |--------------------------------------------------------------------------
            | Học tập
            |--------------------------------------------------------------------------
            */

            '/Hoc luc/u' => 'Học lực',
            '/Hanh kiem/u' => 'Hạnh kiểm',

            '/Tot nghiep/u' => 'Tốt nghiệp',

            '/Cong tac/u' => 'Công tác',

            '/Sinh vien/u' => 'Sinh viên',

            /*
            |--------------------------------------------------------------------------
            | Dân tộc
            |--------------------------------------------------------------------------
            */

            '/Dan toc/u' => 'Dân tộc',

            /*
            |--------------------------------------------------------------------------
            | CCCD
            |--------------------------------------------------------------------------
            */

            '/QUHC/u' => 'QLHC',
            '/QULHC/u' => 'QLHC',
            '/QIHC/u' => 'QLHC',
            '/QLHG/u' => 'QLHC',

            /*
            |--------------------------------------------------------------------------
            | Đại học
            |--------------------------------------------------------------------------
            */

            '/DH/u' => 'Đại học',

            /*
            |--------------------------------------------------------------------------
            | OCR rác cuối câu
            |--------------------------------------------------------------------------
            */

            '/\s+[ai4]\s*$/u' => '',

            '/\s+Be$/u' => '',

            '/\s+ce$/u' => '',

            '/\s+si$/u' => '',

            '/\s+Za$/u' => '',

            '/\s+n\s*%\s*/u' => '',

            /*
            |--------------------------------------------------------------------------
            | Dấu ngoặc
            |--------------------------------------------------------------------------
            */

            '/[`´]/u' => '',

            '/[“”]/u' => '"',

            '/[‘’]/u' => "'",

            /*
            |--------------------------------------------------------------------------
            | OCR ký tự
            |--------------------------------------------------------------------------
            */

            '/\|/u' => ' ',

            '/¦/u' => ' ',

            '/_/u' => ' ',

            '/…/u' => ' ',

            /*
            |--------------------------------------------------------------------------
            | Ngành
            |--------------------------------------------------------------------------
            */

            '/Ngon Ngu Anh/u' => 'Ngôn ngữ Anh',

            '/Ngon ngu Anh/u' => 'Ngôn ngữ Anh',

            '/Ngôn Ngữ Anh/u' => 'Ngôn ngữ Anh',

            '/Nụ\s*i/u' => 'Ngữ',

            '/Ngữ\s*i/u' => 'Ngữ',

            '/Ngũ\s*i/u' => 'Ngữ',

            '/Ngử/u' => 'Ngữ',

            '/Ngư/u' => 'Ngữ',

            /*
            |--------------------------------------------------------------------------
            | Tiếng Việt
            |--------------------------------------------------------------------------
            */

            '/Tran/u' => 'Trần',

            '/Tien/u' => 'Tiền',

            '/Dong/u' => 'Đồng',

            '/Can Tho/u' => 'Cần Thơ',

            '/My Phong/u' => 'Mỹ Phong',

            '/Phuoc/u' => 'Phước',

            '/Thanh pho/u' => 'Thành phố',

            '/duong/u' => 'đường',

            /*
            |--------------------------------------------------------------------------
            | Học lực
            |--------------------------------------------------------------------------
            */

            '/Kha\s*1/u' => 'Khá',

            '/Kha\s*\|/u' => 'Khá',

            '/Gioi/u' => 'Giỏi',

            '/Tot/u' => 'Tốt',

        ];

        foreach ($rules as $pattern => $replace) {
            $text = preg_replace($pattern, $replace, $text);
        }

        /*
        |--------------------------------------------------------------------------
        | Xóa ký tự OCR lẻ
        |--------------------------------------------------------------------------
        */

        $text = preg_replace('/\s+[a-zA-Z]\s+(?=\n)/u', '', $text);

        $text = preg_replace('/\s{2,}/u', ' ', $text);

        $text = preg_replace('/\n{3,}/u', "\n\n", $text);

        /*
        |--------------------------------------------------------------------------
        | Xóa số OCR cuối dòng
        |--------------------------------------------------------------------------
        */

        $text = preg_replace('/([^\d])\s+[123456789]\s*$/mu', '$1', $text);

        /*
        |--------------------------------------------------------------------------
        | Chuẩn hóa khoảng trắng
        |--------------------------------------------------------------------------
        */

        $text = preg_replace('/[ ]{2,}/u', ' ', $text);

        return trim($text);
    }
}